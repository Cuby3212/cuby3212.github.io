CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY CHECK (id = 1), value INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO totals (id, value) VALUES (1, 0);
CREATE TABLE IF NOT EXISTS visits (token TEXT PRIMARY KEY, day TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS visits_day ON visits(day);
CREATE TRIGGER IF NOT EXISTS count_visit AFTER INSERT ON visits BEGIN UPDATE totals SET value = value + 1 WHERE id = 1; END;
